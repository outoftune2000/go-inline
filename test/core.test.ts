import test from 'node:test';
import assert from 'node:assert/strict';
import { boundContext, cleanCompletion, generated, delay, Scheduler } from '../src/core';

test('bounds large input while retaining cursor prefix, suffix, and imports', () => {
  const text = 'package demo\nimport "fmt"\n' + 'x'.repeat(30000) + '\nfunc f() {\n\t' + '\n}\n' + 'y'.repeat(10000);
  const offset = text.indexOf('\n}\n');
  const c = boundContext(text, offset, 'type User struct { Name string }', 4000);
  assert.ok(c.prefix.endsWith('func f() {\n\t'));
  assert.ok(c.suffix.startsWith('\n}\n'));
  assert.match(c.declarations, /import "fmt"/);
  assert.match(c.declarations, /type User/);
  assert.ok(c.prefix.length + c.suffix.length + c.declarations.length <= 11000);
});
test('cleans fenced Go and preserves indentation and CRLF', () => {
  assert.equal(cleanCompletion('```go\n\tif ok {\n\t\treturn nil\n\t}\n```', 'func f() {\n\t', '\n}', true), 'if ok {\r\n\t\treturn nil\r\n\t}');
});
test('removes echoed current line and existing suffix', () => {
  assert.equal(cleanCompletion('return x + y\n}', 'func add() {\nreturn ', '\n}'), 'x + y');
  assert.equal(cleanCompletion('value\n}\n', '\treturn ', '\n}\n'), 'value');
  assert.equal(cleanCompletion('b }\nfunc Sub(a,b int) int { return a - b', 'return a + ', ' }\n'), 'b');
});
test('rejects prose, reasoning, empty output and model tokens', () => {
  for (const value of ['Here is the code:\nreturn nil', '<think>hmm</think>return nil', 'Sure, use this', '   ']) assert.equal(cleanCompletion(value, '', ''), '');
  assert.equal(cleanCompletion('return nil<|endoftext|>', '', ''), 'return nil');
});
test('handles Unicode text and partial expressions', () => {
  assert.equal(cleanCompletion('"नमस्ते"', 'return ', '\n}'), '"नमस्ते"');
  assert.equal(cleanCompletion('count + 1', 'return ', '\n}'), 'count + 1');
});
test('keeps nested unindented braces and suffix-like text inside Go strings', () => {
  const prefix = 'package demo\nfunc f() {\n';
  const loop = 'for i := 0; i < 2; i++ {\nprintln(i)\n}\nreturn';
  assert.equal(cleanCompletion(loop + '\n}\n', prefix, '\n}\n'), loop);
  assert.equal(cleanCompletion('if ok {\nreturn\n}', prefix, '\n}'), 'if ok {\nreturn\n}');
  const raw = 'println(`text\n}\nmore`)\nreturn';
  assert.equal(cleanCompletion(raw + '\n}\n', prefix, '\n}\n'), raw);
});
test('detects canonical generated-file marker only', () => {
  assert.ok(generated('// Code generated by tool. DO NOT EDIT.\npackage demo'));
  assert.ok(!generated('// Please edit this\npackage demo'));
});
test('scheduler debounces rapid requests and serializes active tasks', async () => {
  const scheduler = new Scheduler();
  const started: number[] = [];
  const first = scheduler.run(new AbortController().signal, 30, 500, async () => { started.push(1); return 1; });
  const rejected = assert.rejects(first);
  const second = scheduler.run(new AbortController().signal, 0, 500, async () => { started.push(2); return 2; });
  await rejected;
  assert.equal(await second, 2);
  assert.deepEqual(started, [2]);
  let active = 0;
  const a = scheduler.run(new AbortController().signal, 0, 1000, async signal => {
    active++; try { await delay(200, signal); } finally { active--; }
  });
  const aRejected = assert.rejects(a);
  await new Promise(r => setTimeout(r, 20));
  await scheduler.run(new AbortController().signal, 0, 1000, async () => { assert.equal(active, 0); });
  await aRejected;
});
test('scheduler applies timeout and external cancellation', async () => {
  const scheduler = new Scheduler();
  await assert.rejects(scheduler.run(new AbortController().signal, 0, 10, s => delay(500, s)));
  const c = new AbortController(); c.abort();
  await assert.rejects(scheduler.run(c.signal, 0, 100, async () => 1));
});
test('an already cancelled request does not supersede a valid active generation', async () => {
  const scheduler = new Scheduler();
  let started!: () => void; const ready = new Promise<void>(r => { started = r; });
  const active = scheduler.run(new AbortController().signal, 0, 1000, async s => { started(); await delay(15, s); return 'valid'; });
  await ready;
  const cancelled = new AbortController(); cancelled.abort();
  await assert.rejects(scheduler.run(cancelled.signal, 0, 1000, async () => 'unused'));
  assert.equal(await active, 'valid');
});
