import * as vscode from 'vscode';
import * as assert from 'node:assert/strict';
import * as path from 'node:path';
import { writeFile } from 'node:fs/promises';
import { ContextCollector } from '../../src/context';

export async function run(): Promise<void> {
  const folder = vscode.workspace.workspaceFolders![0].uri.fsPath;
  const main = vscode.Uri.file(path.join(folder, 'main.go'));
  const other = vscode.Uri.file(path.join(folder, 'types.go'));
  const extension = vscode.extensions.getExtension('go-inline-local.go-inline');
  assert.ok(extension, 'extension was discovered');
  await extension.activate(); assert.ok(extension.isActive);
  const commands = await vscode.commands.getCommands(true);
  for (const name of ['toggle', 'selectProvider', 'setApiKey', 'setOpenRouterApiKey', 'checkConnection', 'completeLong']) assert.ok(commands.includes('goInline.' + name));
  const c = vscode.workspace.getConfiguration('goInline');
  assert.equal(c.get('provider'), 'llamacpp');
  await c.update('enabled', true, vscode.ConfigurationTarget.Global);
  const wasEnabled = true;
  await vscode.commands.executeCommand('goInline.toggle'); assert.equal(vscode.workspace.getConfiguration('goInline').get('enabled'), !wasEnabled);
  await vscode.commands.executeCommand('goInline.toggle'); assert.equal(vscode.workspace.getConfiguration('goInline').get('enabled'), wasEnabled);
  console.log('HOST PASS: activation, defaults, commands, and enable toggle');

  const document = await vscode.workspace.openTextDocument(main);
  const otherDoc = await vscode.workspace.openTextDocument(other);
  await vscode.window.showTextDocument(document);
  const go = vscode.extensions.getExtension('golang.go');
  if (!go || !process.env.GO_EXTENSION_PATH) {
  const definition = vscode.languages.registerDefinitionProvider({ language: 'go' }, {
    provideDefinition() { return new vscode.Location(other, new vscode.Range(1, 5, 1, 9)); }
  });
  const symbols = vscode.languages.registerDocumentSymbolProvider({ language: 'go' }, {
    provideDocumentSymbols(doc) {
      if (doc.uri.toString() !== other.toString()) return [];
      return [new vscode.DocumentSymbol('User', '', vscode.SymbolKind.Struct, new vscode.Range(1, 0, 1, doc.lineAt(1).text.length), new vscode.Range(1, 5, 1, 9))];
    }
  });
  const collector = new ContextCollector();
  try {
    const position = document.positionAt(document.getText().indexOf('/*CURSOR*/'));
    const collect = () => collector.collect(document, position, 4000, true, new AbortController().signal);
    assert.match((await collect()).declarations, /Name string/);
    const edit = new vscode.WorkspaceEdit(); edit.replace(other, new vscode.Range(1, 0, 1, otherDoc.lineAt(1).text.length), 'type User struct { Email string }');
    await vscode.workspace.applyEdit(edit);
    assert.match((await collect()).declarations, /Email string/, 'unsaved changes invalidate cache');
    const ignoredEdit = new vscode.WorkspaceEdit(); ignoredEdit.insert(other, new vscode.Position(0, 0), '// Code generated by test. DO NOT EDIT.\n');
    await vscode.workspace.applyEdit(ignoredEdit);
    assert.ok(!(await collect()).declarations.includes('Email string'), 'generated declarations excluded');
    console.log('HOST PASS: symbol/definition context, unsaved edits, cache invalidation, generated-file exclusion');
  } finally { collector.dispose(); definition.dispose(); symbols.dispose(); }

  // Separate fresh collector verifies ignored-file filtering without cached declarations.
  const restore = new vscode.WorkspaceEdit();
  restore.replace(other, new vscode.Range(0, 0, otherDoc.lineCount, 0), 'package demo\ntype User struct { Secret string }\n');
  await vscode.workspace.applyEdit(restore);
  await writeFile(path.join(folder, '.gitignore'), 'types.go\n');
  await otherDoc.save();
  const ignoredCollector = new ContextCollector();
  const fallbackDefinition = vscode.languages.registerDefinitionProvider({ language: 'go' }, { provideDefinition() { return new vscode.Location(other, new vscode.Position(1, 5)); } });
  try {
    const result = await ignoredCollector.collect(document, document.positionAt(document.getText().indexOf('/*CURSOR*/')), 4000, true, new AbortController().signal);
    assert.ok(!result.declarations.includes('Secret string'));
    console.log('HOST PASS: ignored-file filtering and active-file fallback');
  } finally { fallbackDefinition.dispose(); ignoredCollector.dispose(); }
  const outside = vscode.Uri.file(path.join(folder, '..', 'external.go'));
  await writeFile(outside.fsPath, 'package demo\ntype ExternalSecret struct { Token string }\n');
  const externalDefinition = vscode.languages.registerDefinitionProvider({ language: 'go' }, { provideDefinition() { return new vscode.Location(outside, new vscode.Position(1, 5)); } });
  const externalCollector = new ContextCollector();
  try {
    const result = await externalCollector.collect(document, document.positionAt(document.getText().indexOf('/*CURSOR*/')), 4000, true, new AbortController().signal);
    assert.ok(!result.declarations.includes('ExternalSecret'));
    console.log('HOST PASS: declarations outside the workspace are excluded');
  } finally { externalDefinition.dispose(); externalCollector.dispose(); }
  }
  if (go && process.env.GO_EXTENSION_PATH) {
    await writeFile(path.join(folder, '.gitignore'), '');
    await go.activate();
    const settings = vscode.workspace.getConfiguration('go');
    await settings.update('toolsManagement.autoUpdate', false, vscode.ConfigurationTarget.Global);
    await settings.update('toolsManagement.checkForUpdates', 'off', vscode.ConfigurationTarget.Global);
    const edit = new vscode.WorkspaceEdit();
    const source = 'package demo\nfunc NewUser() User { return User{} }\nfunc Broken() int { return "wrong" }\n';
    edit.replace(main, new vscode.Range(0, 0, document.lineCount, 0), source);
    await vscode.workspace.applyEdit(edit); await document.save();
    const deadline = Date.now() + 30000;
    while (Date.now() < deadline && !vscode.languages.getDiagnostics(main).some(d => d.severity === vscode.DiagnosticSeverity.Error && d.message.includes('wrong'))) {
      await new Promise(r => setTimeout(r, 250));
    }
    assert.ok(vscode.languages.getDiagnostics(main).some(d => d.severity === vscode.DiagnosticSeverity.Error && d.message.includes('wrong')), 'gopls reports a type error alongside Go Inline: ' + vscode.languages.getDiagnostics(main).map(d => d.message).join('; '));
    // Navigate the return type, rather than the User substring in NewUser.
    const typeDefinitions = await vscode.commands.executeCommand<vscode.Location[]>('vscode.executeDefinitionProvider', main, document.positionAt(document.getText().indexOf(') User') + 2));
    assert.ok(typeDefinitions?.length, 'gopls navigation still works');
    const unformatted = new vscode.WorkspaceEdit(); unformatted.replace(main, new vscode.Range(0, 0, document.lineCount, 0), source);
    await vscode.workspace.applyEdit(unformatted);
    const formats = await vscode.commands.executeCommand<vscode.TextEdit[]>('vscode.executeFormatDocumentProvider', main, { tabSize: 4, insertSpaces: false });
    assert.ok(formats?.length, 'gopls formatting still works');
    const completionSource = source.replace('return User{}', 'return Use');
    const completionEdit = new vscode.WorkspaceEdit(); completionEdit.replace(main, new vscode.Range(0, 0, document.lineCount, 0), completionSource);
    await vscode.workspace.applyEdit(completionEdit);
    const completions = await vscode.commands.executeCommand<vscode.CompletionList>('vscode.executeCompletionItemProvider', main, document.positionAt(completionSource.indexOf('return Use') + 'return Use'.length));
    assert.ok(completions?.items.some(item => (typeof item.label === 'string' ? item.label : item.label.label).includes('User')), 'gopls standard completion still works');
    console.log('HOST PASS: official Go/gopls coexistence — type diagnostics, definition navigation, formatting, and completion');
  } else console.log('Official Go/gopls coexistence not exercised in this isolated profile. Set GO_EXTENSION_PATH to test it.');
}
